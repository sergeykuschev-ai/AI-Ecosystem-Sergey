/* eslint-disable @typescript-eslint/no-require-imports -- Opt-in read-only browser checks. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright-core')
const base = process.env.VOZDOOH_QA_URL || 'http://127.0.0.1:3438'
;(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, headless: true, args: ['--no-sandbox'], ...(process.env.VOZDOOH_QA_PROXY ? { proxy: { server: process.env.VOZDOOH_QA_PROXY } } : {}) })
  try {
    for (const width of [390, 1280]) {
      const context = await browser.newContext({ viewport: { width, height: 900 } })
      const page = await context.newPage()
      const errors = []
      page.on('pageerror', error => errors.push(error.message))
      await page.route('**/*', route => {
        const request = route.request()
        return request.method() === 'GET' && new URL(request.url()).origin === new URL(base).origin ? route.continue() : route.abort()
      })
      const visit = async (query = '') => { const response = await page.goto(`${base}/catalog${query}`, { waitUntil: 'domcontentloaded' }); assert.equal(response.status(), 200) }
      const cards = page.locator('.catalogGrid .productCard')
      const search = page.getByRole('searchbox', { name: 'Поиск по названию или бренду' })
      await visit()
      const originalCount = await cards.count()
      assert.ok(originalCount > 0)
      assert.ok(await search.isVisible())
      const name = await cards.first().getAttribute('title')
      const brand = (await cards.first().locator('.productCardMeta > span').first().innerText()).trim()
      assert.ok(brand)
      await search.fill(name.toLowerCase().replace(/\s+/g, '  '))
      await page.getByRole('button', { name: 'Найти', exact: true }).click()
      await page.waitForLoadState('domcontentloaded')
      assert.ok(new URL(page.url()).searchParams.has('q'))
      assert.ok(await cards.count() > 0)
      assert.equal(await page.locator('link[rel="canonical"]').getAttribute('href'), 'https://vozdooh27.ru/catalog')
      assert.match(await page.locator('meta[name="robots"]').getAttribute('content'), /noindex/)
      await visit(`?q=${encodeURIComponent(brand.toLowerCase())}`)
      assert.ok(await cards.count() > 0)
      for (const text of await cards.locator('.productCardMeta > span:first-child').allTextContents()) assert.ok(text.toLowerCase().includes(brand.toLowerCase()))
      await page.locator('.filterDisclosure summary').click()
      const category = await page.locator('select[name="category"] option').evaluateAll(options => options.find(o => o.value)?.value)
      assert.ok(category)
      await page.locator('select[name="category"]').selectOption(category)
      await page.getByRole('button', { name: 'Показать ароматы' }).click()
      await page.waitForLoadState('domcontentloaded')
      assert.equal(new URL(page.url()).searchParams.get('q'), brand.toLowerCase())
      assert.equal(new URL(page.url()).searchParams.get('category'), category)
      await search.fill('zzzz-no-such-product-20261014')
      await page.getByRole('button', { name: 'Найти', exact: true }).click()
      await page.waitForLoadState('domcontentloaded')
      assert.equal(await cards.count(), 0)
      assert.ok(await page.getByRole('heading', { name: 'Ничего не найдено' }).isVisible())
      assert.equal(new URL(page.url()).searchParams.get('category'), category)
      await Promise.all([page.waitForURL(url => !url.searchParams.has('q')), page.getByRole('link', { name: 'Сбросить поиск', exact: true }).first().click()])
      await page.waitForFunction(() => document.querySelector('#catalog-search')?.value === '')
      assert.equal(new URL(page.url()).searchParams.has('q'), false)
      assert.equal(new URL(page.url()).searchParams.get('category'), category)
      if (process.env.VOZDOOH_QA_SKU) {
        await visit(`?q=${encodeURIComponent(process.env.VOZDOOH_QA_SKU)}`)
        assert.ok(await cards.count() > 0)
      }
      await visit('?q=445445')
      assert.equal(await cards.count(), 0)
      await visit('?q=%20%20')
      assert.equal(await cards.count(), originalCount)
      assert.match(await page.locator('meta[name="robots"]').getAttribute('content'), /noindex/)
      await visit()
      const bounds = await search.boundingBox()
      assert.ok(bounds.width > 200)
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
      await page.screenshot({ path: `/tmp/vozdooh-search-${width}.png`, fullPage: false })
      assert.deepEqual(errors, [])
      console.log(`PASS ${width}px: search, brand, filters, empty/reset, hidden SKU, canonical/noindex, layout`)
      await context.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
