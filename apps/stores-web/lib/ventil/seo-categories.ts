export const VENTIL_SEO_CATEGORY_PATHS = VENTIL_SEO_CATEGORIES.map(
  (category) => `/ventil/${category.slug}/`,
);

export function getVentilSeoCategory(slug: string): VentilSeoCategory {
  const category = VENTIL_SEO_CATEGORIES.find((item) => item.slug === slug);
  if (!category) throw new Error(`Unknown Ventil SEO category: ${slug}`);
  return category;
}
