export const METIZ_SEO_CATEGORY_PATHS = METIZ_SEO_CATEGORIES.map(
  (category) => `/metiz-market/${category.slug}/`,
);

export function getMetizSeoCategory(slug: string): MetizSeoCategory {
  const category = METIZ_SEO_CATEGORIES.find((item) => item.slug === slug);
  if (!category) throw new Error(`Unknown Metiz SEO category: ${slug}`);
  return category;
}
