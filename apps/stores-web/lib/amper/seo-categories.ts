export const AMPER_SEO_CATEGORY_PATHS = AMPER_SEO_CATEGORIES.map(
  (category) => `/amper/${category.slug}/`,
);

export function getAmperSeoCategory(slug: string): AmperSeoCategory {
  const category = AMPER_SEO_CATEGORIES.find((item) => item.slug === slug);
  if (!category) throw new Error(`Unknown Amper SEO category: ${slug}`);
  return category;
}
